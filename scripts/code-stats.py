#!/usr/bin/env python3
"""Line counts for two GETSSH revisions and the diff between them, as in the README.

    python3 scripts/code-stats.py v2.0.0_R7K4S v3.0.0-preview
    python3 scripts/code-stats.py v2.0.0_R7K4S v3.0.0-preview --json

Reads git objects only: nothing is checked out and no file is written.

- Added and deleted lines come from `git diff -M`, so files that moved (2.0 kept the app at the
  repository root, 3.0 under apps/getssh-client/) are compared with their old selves. A file
  less than half similar to its old self counts as deleted plus added.
- Not counted: lockfiles, binary files, vendored third-party source (any vendor/ directory, i.e.
  SQLite3MultipleCiphers in rust-core/getssh-store/vendor/), and the loaders napi-rs generates
  (rust-core/*/index.js and index.d.ts headed "auto-generated by NAPI-RS" or "tslint:disable").
- "Lines" includes blank lines and comments. "Code" leaves out blank lines and lines that hold only
  a comment (a heuristic per language).
- Tests: files named *.test.* or *.spec.*, or under tests/, __tests__/ or e2e/, or *.conformance.*.
  Rust unit tests inside source files (#[cfg(test)]) count with the Rust modules.
"""
import json
import os
import re
import subprocess
import sys
from collections import defaultdict

LOCKFILES = {'pnpm-lock.yaml', 'Cargo.lock', 'package-lock.json', 'yarn.lock'}
BINARY_EXT = {'.png', '.jpg', '.jpeg', '.gif', '.ico', '.icns', '.webp', '.ttf', '.otf', '.woff', '.woff2',
              '.dmg', '.zip', '.mp4', '.pdf', '.node', '.exe', '.dll'}
LANG = {'.ts': 'TypeScript', '.tsx': 'TypeScript', '.mts': 'TypeScript', '.cts': 'TypeScript', '.d.ts': 'TypeScript',
        '.js': 'JavaScript', '.jsx': 'JavaScript', '.cjs': 'JavaScript', '.mjs': 'JavaScript',
        '.rs': 'Rust', '.swift': 'Swift', '.c': 'C/C++', '.h': 'C/C++', '.cc': 'C/C++', '.cpp': 'C/C++',
        '.css': 'CSS', '.html': 'HTML', '.sh': 'Shell', '.ps1': 'PowerShell', '.bat': 'Batch', '.py': 'Python',
        '.md': 'Markdown', '.json': 'Config', '.yaml': 'Config', '.yml': 'Config', '.toml': 'Config',
        '.plist': 'Config', '.xml': 'Config', '.sb': 'Seatbelt'}
SOURCE_LANGS = {'TypeScript', 'JavaScript', 'Rust', 'Swift', 'C/C++', 'CSS', 'HTML', 'Shell', 'PowerShell',
                'Batch', 'Python', 'Seatbelt'}
AREAS = ['Main process (electron/)', 'Interface (src/)', 'Rust modules (rust-core/)', 'Tests', 'Scripts and build',
         'CI', 'Plugins and examples', 'Other (root config etc.)', 'Docs']


def git(repo, *args, data=None):
    return subprocess.run(['git', '-C', repo, *args], capture_output=True, input=data, check=True).stdout


def ext(path):
    base = os.path.basename(path)
    return '.d.ts' if base.endswith('.d.ts') else os.path.splitext(base)[1].lower()


def area(path):
    p = path[len('apps/getssh-client/'):] if path.startswith('apps/getssh-client/') else path
    if ext(path) == '.md' or p.startswith('docs/'):
        return 'Docs'
    if p.startswith('.github/'):
        return 'CI'
    if re.search(r'(\.test\.|\.spec\.|(^|/)tests?/|__tests__|\.conformance\.|(^|/)e2e/)', p):
        return 'Tests'
    for prefix, name in (('electron/', 'Main process (electron/)'), ('src/', 'Interface (src/)'),
                         ('rust-core/', 'Rust modules (rust-core/)'), ('plugins/', 'Plugins and examples'),
                         ('test-plugins/', 'Plugins and examples'), ('scripts/', 'Scripts and build'),
                         ('build/', 'Scripts and build'), ('patches/', 'Scripts and build')):
        if p.startswith(prefix):
            return name
    return 'Other (root config etc.)'


def comment_only(line, lang):
    s = line.strip()
    if lang in ('Shell', 'PowerShell', 'Python', 'Config'):
        return s.startswith('#')
    if lang == 'Batch':
        return s.upper().startswith('REM') or s.startswith('::')
    if lang == 'Seatbelt':
        return s.startswith(';')
    if lang == 'HTML':
        return s.startswith('<!--')
    return s.startswith(('//', '/*', '*'))


def read_revision(repo, rev):
    """Path -> (content, reason it is not counted or None)."""
    files = {}
    for entry in git(repo, 'ls-tree', '-r', '-z', '--full-tree', rev).split(b'\0'):
        if not entry:
            continue
        meta, path = entry.split(b'\t', 1)
        mode, kind, sha = meta.split()
        if kind == b'blob' and mode != b'120000':
            files[path.decode()] = sha.decode()
    batch = git(repo, 'cat-file', '--batch', data=('\n'.join(files.values()) + '\n').encode())
    out, i = {}, 0
    for path in files:
        nl = batch.index(b'\n', i)
        size = int(batch[i:nl].split()[2])
        content = batch[nl + 1:nl + 1 + size]
        i = nl + 1 + size + 1
        out[path] = content
    result = {}
    for path, content in out.items():
        base, head = os.path.basename(path), b'\n'.join(content.split(b'\n')[:5])
        why = None
        if base in LOCKFILES:
            why = 'lockfile'
        elif ext(path) in BINARY_EXT or b'\0' in content[:8000]:
            why = 'binary'
        elif '/vendor/' in path or path.startswith('vendor/'):
            why = 'vendored'
        elif b'auto-generated by NAPI-RS' in head or (path.startswith('rust-core/') and b'tslint:disable' in head):
            why = 'generated napi loader'
        result[path] = (content, why)
    return result


def sizes(files):
    by_area = defaultdict(lambda: {'files': 0, 'lines': 0, 'code': 0})
    by_lang = defaultdict(lambda: {'files': 0, 'lines': 0, 'code': 0})
    excluded = defaultdict(lambda: {'files': 0, 'lines': 0})
    for path, (content, why) in files.items():
        lines = content.decode('utf-8', 'replace').splitlines()
        if why:
            excluded[why]['files'] += 1
            excluded[why]['lines'] += len(lines)
            continue
        lang = LANG.get(ext(path), 'Other text')
        code = sum(1 for l in lines if l.strip() and not comment_only(l, lang))
        for table, key in ((by_area, area(path)), (by_lang, lang)):
            table[key]['files'] += 1
            table[key]['lines'] += len(lines)
            table[key]['code'] += code
    return by_area, by_lang, excluded


def diff(repo, old_rev, new_rev, old_files, new_files):
    by_area = defaultdict(lambda: {'files': 0, 'added': 0, 'deleted': 0})
    excluded = defaultdict(lambda: {'added': 0, 'deleted': 0})
    fields = git(repo, 'diff', '-M', '--numstat', '-z', old_rev, new_rev).split(b'\0')
    i = 0
    while i < len(fields):
        if not fields[i]:
            i += 1
            continue
        added, deleted, path = fields[i].decode().split('\t')
        if path == '':  # a rename: old and new path follow
            old, new = fields[i + 1].decode(), fields[i + 2].decode()
            i += 3
        else:
            old = new = path
            i += 1
        why = (new_files.get(new) or old_files.get(old) or (b'', None))[1]
        if added == '-':
            why = why or 'binary'
        if why:
            excluded[why]['added'] += int(added) if added != '-' else 0
            excluded[why]['deleted'] += int(deleted) if deleted != '-' else 0
            continue
        row = by_area[area(new if new in new_files else old)]
        row['files'] += 1
        row['added'] += int(added)
        row['deleted'] += int(deleted)
    return by_area, excluded


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    if len(args) != 2:
        sys.exit(__doc__)
    repo = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    old_rev, new_rev = args
    old_files, new_files = read_revision(repo, old_rev), read_revision(repo, new_rev)
    old_area, old_lang, old_excl = sizes(old_files)
    new_area, new_lang, new_excl = sizes(new_files)
    diff_area, diff_excl = diff(repo, old_rev, new_rev, old_files, new_files)
    report = {
        'old': old_rev, 'new': new_rev,
        'commits': int(git(repo, 'rev-list', '--count', f'{old_rev}..{new_rev}').decode()),
        'raw_shortstat': git(repo, 'diff', '-M', '--shortstat', old_rev, new_rev).decode().strip(),
        'by_area': {a: {'old': old_area.get(a), 'new': new_area.get(a), 'diff': diff_area.get(a)} for a in AREAS},
        'by_language': {l: {'old': old_lang.get(l), 'new': new_lang.get(l)} for l in sorted(set(old_lang) | set(new_lang))},
        'not_counted': {'old': old_excl, 'new': new_excl, 'diff': diff_excl},
    }
    if '--json' in sys.argv:
        print(json.dumps(report, indent=1))
        return
    z = {'files': 0, 'lines': 0, 'code': 0, 'added': 0, 'deleted': 0}
    print(f"{old_rev} -> {new_rev}: {report['commits']} commits; git without filters: {report['raw_shortstat']}\n")
    print(f"{'part':28} {'files':>11} {'lines':>17} {'added':>8} {'deleted':>8}")
    tot = defaultdict(int)
    for a in AREAS:
        o, n, d = old_area.get(a, z), new_area.get(a, z), diff_area.get(a, z)
        print(f"{a:28} {o['files']:>5}->{n['files']:<5} {o['lines']:>8}->{n['lines']:<8} {d['added']:>8} {d['deleted']:>8}")
        for k, v in (('of', o['files']), ('nf', n['files']), ('ol', o['lines']), ('nl', n['lines']),
                     ('a', d['added']), ('d', d['deleted'])):
            tot[k] += v
    print(f"{'total':28} {tot['of']:>5}->{tot['nf']:<5} {tot['ol']:>8}->{tot['nl']:<8} {tot['a']:>8} {tot['d']:>8}\n")
    print('code lines (no blank or comment-only lines) by language:')
    for lang in sorted(report['by_language'], key=lambda l: -(new_lang.get(l, z)['code'])):
        if lang in SOURCE_LANGS:
            o, n = old_lang.get(lang, z), new_lang.get(lang, z)
            print(f"  {lang:12} {o['files']:>4} -> {n['files']:<4} files  {o['code']:>7} -> {n['code']:<7}")
    print('\nnot counted:', json.dumps(report['not_counted']['diff']))


if __name__ == '__main__':
    main()
